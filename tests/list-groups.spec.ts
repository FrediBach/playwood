import { test, expect, type Page, type Locator } from '@playwright/test'

async function dragTo(page: Page, handle: Locator, target: Locator) {
  await handle.scrollIntoViewIfNeeded()
  const source = await handle.boundingBox()
  const destination = await target.boundingBox()
  expect(source).not.toBeNull()
  expect(destination).not.toBeNull()
  await page.mouse.move(source!.x + source!.width / 2, source!.y + source!.height / 2)
  await page.mouse.down()
  await page.mouse.move(destination!.x + destination!.width / 2, destination!.y + destination!.height / 2, { steps: 12 })
  await page.mouse.up()
}
async function nameGroup(page: Page, name: string) {
  const input = page.getByRole('textbox', { name: 'Rename group', exact: true })
  await expect(input).toBeFocused()
  await input.fill(name)
  await input.press('Enter')
}
function group(page: Page, name: string) {
  return page.locator('.named-group').filter({ has: page.locator('.list-group-name', { hasText: name }) })
}

test('panel grouping supports context selection, rename, moving in/out, collapse, undo and persistence', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('checkbox', { name: 'Select Left side', exact: true }).check()
  await page.locator('.panel-list-select').first().click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Group selected', exact: true }).click()
  await nameGroup(page, 'Frame')
  await expect(group(page, 'Frame').locator('.panel-list-row')).toHaveCount(2)
  await expect(page.locator('.panel-list-row.selected')).toHaveCount(2)
  await page.getByRole('button', { name: 'Rename group Frame', exact: true }).click()
  await page.getByRole('textbox', { name: 'Rename group', exact: true }).fill('Cancel me')
  await page.keyboard.press('Escape')
  await expect(group(page, 'Frame')).toBeVisible()
  await page.getByRole('button', { name: 'Collapse group Frame', exact: true }).click()
  await dragTo(page, page.getByRole('button', { name: 'Reorder Right side', exact: true }), group(page, 'Frame').locator('.list-group-header'))
  await expect(group(page, 'Frame').locator('.panel-list-row')).toHaveCount(3)
  await expect(page.locator('.panel-list-row')).toHaveCount(7)
  // A selected row moves the entire selection out, even if another item was just dragged in.
  await dragTo(page, page.getByRole('button', { name: 'Reorder Bottom shelf', exact: true }), page.locator('.list-ungrouped-label'))
  await expect(group(page, 'Frame').locator('.panel-list-row')).toHaveCount(1)
  await page.getByRole('button', { name: 'Undo (⌘/Ctrl Z)', exact: true }).click()
  await expect(group(page, 'Frame').locator('.panel-list-row')).toHaveCount(3)
  await expect(page.getByText('Saved on this device', { exact: true })).toBeVisible()
  await page.reload()
  await expect(group(page, 'Frame').locator('.panel-list-row')).toHaveCount(3)
  await group(page, 'Frame').locator('.list-group-name').press('F2')
  await nameGroup(page, 'Structure')
  await page.screenshot({ path: 'test-results/panel-groups.png' })
  await group(page, 'Structure').locator('.list-group-name').click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Ungroup', exact: true }).click()
  await expect(page.locator('.named-group')).toHaveCount(0)
  await expect(page.locator('.panel-list-row')).toHaveCount(7)
})

test('connectors can move between empty groups and ungrouped with keyboard and pointer', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('tab', { name: 'Connectors', exact: true }).click()
  await page.locator('.connector-list input[type=checkbox]').nth(0).check()
  await page.locator('.connector-list input[type=checkbox]').nth(1).check()
  await page.locator('.connector-list-select').first().press('Shift+F10')
  await page.getByRole('menuitem', { name: 'Group selected', exact: true }).click()
  await nameGroup(page, 'Corners')
  await expect(group(page, 'Corners').locator('.connector-list-row')).toHaveCount(2)
  await page.getByRole('button', { name: 'New group', exact: true }).click()
  await nameGroup(page, 'Spares')
  await dragTo(page, group(page, 'Corners').locator('.connector-drag-handle').first(), group(page, 'Spares').locator('.list-group-empty'))
  await expect(group(page, 'Corners').locator('.connector-list-row')).toHaveCount(0)
  await expect(group(page, 'Spares').locator('.connector-list-row')).toHaveCount(2)
  await group(page, 'Spares').locator('.connector-drag-handle').first().press('Space')
  await page.keyboard.press('End')
  await page.keyboard.press('Enter')
  await expect(group(page, 'Spares').locator('.connector-list-row')).toHaveCount(0)
  await expect(page.locator('.connector-list-row')).toHaveCount(12)
  await page.getByRole('button', { name: 'Undo (⌘/Ctrl Z)', exact: true }).click()
  await expect(group(page, 'Spares').locator('.connector-list-row')).toHaveCount(2)
  await expect(page.getByText('Saved on this device', { exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('tab', { name: 'Connectors', exact: true }).click()
  await expect(group(page, 'Spares').locator('.connector-list-row')).toHaveCount(2)
  await expect(group(page, 'Corners').locator('.list-group-empty')).toBeVisible()
  await page.screenshot({ path: 'test-results/connector-groups.png' })
})

test('touch dragging moves panels into and out of a group on a phone', async ({ browser, baseURL }) => {
  const context = await browser.newContext({ baseURL, hasTouch: true, isMobile: true, viewport: { width: 390, height: 844 } })
  try {
    const page = await context.newPage()
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('/')
    await page.getByRole('button', { name: 'Open panel list', exact: true }).tap()
    await page.getByRole('button', { name: 'New group', exact: true }).tap()
    await nameGroup(page, 'Shelves')
    const input = await context.newCDPSession(page)
    const touchDrag = async (target: Locator) => {
      const handle = await page.getByRole('button', { name: 'Reorder Bottom shelf', exact: true }).boundingBox()
      const bounds = await target.boundingBox()
      const x = handle!.x + handle!.width / 2, y = handle!.y + handle!.height / 2
      const endY = bounds!.y + bounds!.height / 2
      await input.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] })
      for (let step = 1; step <= 12; step++) await input.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x, y: y + (endY - y) * step / 12 }] })
      await input.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    }
    await touchDrag(group(page, 'Shelves').locator('.list-group-header'))
    await expect(group(page, 'Shelves').locator('.panel-list-row')).toHaveCount(1)
    const toggle = page.getByRole('checkbox', { name: 'Select all panels in Shelves', exact: true })
    await toggle.tap()
    await expect(page.locator('.panel-list-row.selected')).toHaveCount(0)
    await expect(page.getByRole('complementary', { name: 'Project panels' })).toBeVisible()
    await toggle.tap()
    await expect(page.locator('.panel-list-row.selected')).toHaveCount(1)
    await page.screenshot({ path: 'test-results/panel-groups-mobile.png' })
    await touchDrag(page.locator('.list-ungrouped-label'))
    await expect(group(page, 'Shelves').locator('.panel-list-row')).toHaveCount(0)
    await expect(page.locator('.panel-list-row')).toHaveCount(7)
    expect(errors).toEqual([])
  } finally { await context.close() }
})

for (const kind of ['panels', 'connectors'] as const) {
  test(`${kind} group checkbox selects all, reflects partial selection and preserves other selections`, async ({ page }) => {
    await page.goto('/')
    if (kind === 'connectors') await page.getByRole('tab', { name: 'Connectors', exact: true }).click()
    const rowClass = kind === 'panels' ? '.panel-list-row' : '.connector-list-row'
    const rows = page.locator(rowClass)
    await rows.nth(0).getByRole('checkbox').check()
    await rows.nth(1).getByRole('checkbox').check()
    await page.getByRole('button', { name: 'Group selected', exact: true }).click()
    await nameGroup(page, 'Parts')
    const folder = group(page, 'Parts')
    const toggle = page.getByRole('checkbox', { name: `Select all ${kind} in Parts`, exact: true })
    await expect(toggle).toBeChecked()
    await folder.locator(rowClass).first().getByRole('checkbox').uncheck()
    await expect(toggle).toHaveAttribute('aria-checked', 'mixed')
    await expect(toggle).toHaveJSProperty('indeterminate', true)
    const outside = page.locator('[data-list-section=""]').locator(rowClass).first().getByRole('checkbox')
    await outside.check()
    await toggle.click()
    await expect(toggle).toBeChecked()
    await expect(toggle).toHaveJSProperty('indeterminate', false)
    await expect(page.locator(`${rowClass}.selected`)).toHaveCount(3)
    await page.getByRole('button', { name: 'Collapse group Parts', exact: true }).click()
    await toggle.press('Space')
    await expect(toggle).not.toBeChecked()
    await expect(outside).toBeChecked()
    await page.getByRole('button', { name: 'Expand group Parts', exact: true }).click()
    await expect(folder.locator(`${rowClass}.selected`)).toHaveCount(0)
    await page.getByRole('button', { name: 'Collapse group Parts', exact: true }).click()
    await toggle.press('Space')
    await expect(toggle).toBeChecked()
    await page.getByRole('button', { name: 'Expand group Parts', exact: true }).click()
    await expect(folder.locator(`${rowClass}.selected`)).toHaveCount(2)
    await expect(outside).toBeChecked()
    await page.getByRole('button', { name: 'New group', exact: true }).click()
    await nameGroup(page, 'Empty')
    await expect(page.getByRole('checkbox', { name: `Select all ${kind} in Empty`, exact: true })).toBeDisabled()
    await page.screenshot({ path: `test-results/${kind}-group-selection.png` })
  })
}
