import { test, expect } from '@playwright/test'

test('add matching connectors from inspector and context menu, cancel, undo, redo and reload', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('tab', { name: 'Connectors', exact: true }).click()
  await page.locator('.connector-list-select').nth(0).click()
  await page.locator('.connector-list-select').nth(1).click({ modifiers: ['Shift'] })
  const action = page.getByRole('button', { name: 'Add connectors between', exact: true })
  await expect(action).toBeEnabled()
  const before = await page.locator('.connector-list-row').count()
  await action.click()
  const dialog = page.getByRole('dialog', { name: 'Add connectors between' })
  await dialog.getByLabel('Number of connectors').fill('18')
  await expect(dialog.getByRole('button', { name: 'Add connectors', exact: true })).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(page.locator('.connector-list-row')).toHaveCount(before)
  await expect(action).toBeFocused()
  await page.locator('canvas').focus()
  await page.keyboard.press('Shift+F10')
  await page.getByRole('menuitem', { name: 'Add connectors between', exact: true }).click()
  await dialog.getByLabel('Number of connectors').fill('2')
  await dialog.getByRole('button', { name: 'Add connectors', exact: true }).click()
  await expect(page.locator('.connector-list-row')).toHaveCount(before + 2)
  await page.getByRole('button', { name: 'Undo (⌘/Ctrl Z)', exact: true }).click()
  await expect(page.locator('.connector-list-row')).toHaveCount(before)
  await page.getByRole('button', { name: 'Redo (⌘/Ctrl Shift Z)', exact: true }).click()
  await expect(page.locator('.connector-list-row')).toHaveCount(before + 2)
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('playwood-studio-project-v1')!).connections.reduce((sum: number, c: {count: number}) => sum + c.count, 0))).toBe(before + 2)
  await page.reload()
  await page.getByRole('tab', { name: 'Connectors', exact: true }).click()
  await expect(page.locator('.connector-list-row')).toHaveCount(before + 2)
  await page.setViewportSize({ width: 800, height: 800 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
