import { expect, test } from '@playwright/test'
import { createPanel } from '../src/lib/model'

for (const width of [1440, 390]) test(`build space saves, rejects undersized bounds, and reloads at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 1000 })
  await page.goto('/')
  await page.getByLabel('Import project file').setInputFiles({ name: 'space.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ version: 1, name: 'Space', panels: [createPanel({ width: 400, height: 400, position: [0, 200, 0] })], connections: [] })) })
  await page.getByRole('button', { name: 'All constraints', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Build space', exact: true })).toBeVisible()
  await page.getByLabel('Enable build space').check()
  await expect(page.locator('.constraint-overlay-label')).toContainText('Build space')
  await page.getByLabel('Space width', { exact: true }).fill('800')
  await page.getByLabel('Space width', { exact: true }).press('Enter')
  await page.getByLabel('Enable build space').uncheck()
  await expect(page.locator('.constraint-overlay-label')).toHaveCount(0)
  await expect(page.getByLabel('Space width', { exact: true })).toHaveValue('800')
  await page.getByRole('button', { name: 'Undo (⌘/Ctrl Z)' }).click()
  await expect(page.getByLabel('Enable build space')).toBeChecked()
  await expect(page.locator('.constraint-overlay-label')).toContainText('1000 × 1000 × 1000')
  await page.getByLabel('Enable build space').uncheck()
  await page.getByLabel('Enable build space').check()
  await expect(page.getByLabel('Space width', { exact: true })).toHaveValue('800')
  await page.getByLabel('Space width', { exact: true }).fill('300')
  await page.getByLabel('Space width', { exact: true }).press('Enter')
  await page.getByRole('button', { name: 'Save build space' }).click()
  await expect(page.getByRole('alert')).toContainText('build space limit')
  await page.getByLabel('Space width', { exact: true }).fill('400')
  await page.getByLabel('Space width', { exact: true }).press('Enter')
  await page.getByRole('button', { name: 'Save build space' }).click()
  await expect(page.locator('.constraint-overlay-label')).toContainText('Space boundary reached')
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('playwood-studio-project-v1')!).spaceConstraint?.width)).toBe(400)
  await page.screenshot({ path: test.info().outputPath('build-space.png') })
  if (width < 680) await page.getByRole('button', { name: 'Collapse inspector', exact: true }).click()
  await page.getByRole('button', { name: 'Realistic preview', exact: true }).click()
  await expect(page.locator('.constraint-overlay-label')).toHaveCount(0)
  await page.getByRole('button', { name: 'Studio', exact: true }).click()
  await expect(page.locator('.constraint-overlay-label')).toContainText('Space boundary reached')
  await page.getByRole('button', { name: 'Undo (⌘/Ctrl Z)' }).click()
  await expect(page.locator('.constraint-overlay-label')).toContainText('1000 × 1000 × 1000')
  await page.getByRole('button', { name: 'Redo (⌘/Ctrl Shift Z)' }).click()
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('playwood-studio-project-v1')!).spaceConstraint?.enabled)).toBe(true)
  await page.reload()
  await page.getByRole('button', { name: 'All constraints', exact: true }).click()
  await expect(page.getByLabel('Enable build space')).toBeChecked()
  await expect(page.getByLabel('Space width', { exact: true })).toHaveValue('400')
})
