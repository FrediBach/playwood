test('menu shortcuts share actions, preserve field input, and cycle visibility with undo', async ({ page }) => {
  const panel = createPanel({ name: 'Shortcut panel', width: 250, height: 250, position: [0, 500, 0] })
  await page.goto('/')
  await page.getByLabel('Import project file').setInputFiles({ name: 'shortcuts.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ version: 1, name: 'Shortcuts', panels: [panel], connections: [] })) })
  await ready(page)
  const canvas = page.locator('canvas')
  await canvas.focus()
  await page.keyboard.press('Shift+F10')
  const menu = page.getByRole('menu', { name: 'Preview actions' })
  // Submenu triggers open nested items, which carry their own shortcuts.
  expect(await menu.locator('[role="menuitem"]:not([aria-haspopup])').count()).toBe(await menu.locator('kbd').count())
  await expect(menu.getByRole('menuitem', { name: 'Attach a panel', exact: true })).toHaveAttribute('aria-keyshortcuts', 'a')
  await expect(menu.getByRole('menuitem', { name: 'Cycle panel visibility' }).locator('kbd')).toHaveText('V')
  await menu.screenshot({ path: 'test-results/preview-shortcuts-menu.png' })
  await page.keyboard.press('v')
  await expect(menu).toHaveCount(0)
  await expect(canvas).toBeFocused()
  const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('playwood-studio-project-v1')!).panels[0])
  await expect.poll(async () => (await saved()).wireframe).toBe(true)
  await page.keyboard.press('v')
  await expect.poll(async () => (await saved()).wireframe).toBe(false)
  expect((await saved()).visible).toBe(false)
  await page.keyboard.press('v')
  await expect.poll(async () => (await saved()).visible).toBe(true)
  await page.keyboard.press('ControlOrMeta+z')
  await expect.poll(async () => (await saved()).visible).toBe(false)
  await page.getByLabel('Panel name', { exact: true }).fill('v')
  expect((await saved()).visible).toBe(false)
  await canvas.focus()
  await page.keyboard.press('v')
  await page.keyboard.press('Shift+F10')
  await page.keyboard.press('ControlOrMeta+d')
  await expect(menu).toHaveCount(0)
  await expect(page.locator('.panel-list-row')).toHaveCount(2)
  await page.keyboard.press('ControlOrMeta+z')
  await expect(page.locator('.panel-list-row')).toHaveCount(1)
  await page.keyboard.press('ControlOrMeta+a')
  await canvas.focus()
  await page.keyboard.press('Shift+C')
  await expect(page.getByRole('button', { name: 'Add constraint', exact: true })).toBeVisible()
})

test('constraint submenu adds prefilled one-click rules with undo', async ({ page }) => {
  const side = (name: string, x: number) => createPanel({ name, width: 300, height: 500, rotation: [0, Math.PI / 2, 0], position: [x, 250, 0] })
  const panels = [side('Left', -400), side('Middle', -250), side('Right', 400)]
  await page.addInitScript(project => localStorage.setItem('playwood-studio-project-v1', JSON.stringify(project)), { version: 1, name: 'Suggestions', panels, connections: [] })
  await page.goto('/')
  await ready(page)
  await page.keyboard.press('ControlOrMeta+a')
  await page.locator('canvas').focus()
  await page.keyboard.press('Shift+F10')
  const menu = page.getByRole('menu', { name: 'Preview actions' })
  const trigger = menu.getByRole('menuitem', { name: 'Add constraints', exact: true })
  await expect(trigger).toHaveAttribute('aria-haspopup', 'menu')
  await trigger.focus()
  await page.keyboard.press('ArrowRight')
  const submenu = page.getByRole('menu', { name: 'Add constraints' })
  await expect(trigger).toHaveAttribute('aria-expanded', 'true')
  await expect(submenu.getByRole('menuitem', { name: 'Stick to ground', exact: true })).toBeFocused()
  await expect(submenu.getByRole('menuitem', { name: 'Distribute equally', exact: true })).toBeVisible()
  await expect(submenu.getByRole('menuitem', { name: 'Custom constraint…', exact: true })).toBeVisible()
  await page.keyboard.press('ArrowLeft')
  await expect(submenu).toHaveCount(0)
  await expect(trigger).toBeFocused()

  await trigger.hover()
  await submenu.getByRole('menuitem', { name: 'Distribute equally', exact: true }).click()
  await expect(menu).toHaveCount(0)
  const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('playwood-studio-project-v1')!))
  await expect.poll(async () => (await saved()).constraints?.length ?? 0).toBe(1)
  const project = await saved()
  expect(project.constraints[0]).toMatchObject({ kind: 'opening-ratio', ratio: 1, axis: 'x' })
  expect(Math.abs(project.panels.find((panel: { name: string }) => panel.name === 'Middle').position[0])).toBeLessThan(0.01)

  await page.locator('canvas').focus()
  await page.keyboard.press('Shift+F10')
  await trigger.click()
  await expect(submenu.getByRole('menuitem', { name: 'Keep spacing equal' })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(submenu).toHaveCount(0)
  await page.keyboard.press('Escape')
  await page.keyboard.press('ControlOrMeta+z')
  await expect.poll(async () => (await saved()).constraints?.length ?? 0).toBe(0)
  expect((await saved()).panels.find((panel: { name: string }) => panel.name === 'Middle').position[0]).toBe(-250)
})
