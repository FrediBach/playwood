import { test, expect } from '@playwright/test'

test('editor renders, creates panels, previews attachments, saves and undoes', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('group', { name: 'Preview mode' })).toBeVisible()
  await expect(page.locator('canvas')).toBeVisible()
  await expect.poll(()=>page.locator('canvas').evaluate(canvas=>(canvas as HTMLCanvasElement).toDataURL().length),{timeout:15000}).toBeGreaterThan(30000)
  await page.screenshot({ path: 'test-results/studio-desktop.png' })
  const initialCount = await page.locator('.panel-list-row').count()
  await page.getByRole('button', { name: 'Add a panel', exact: false }).first().click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('dialog').getByText('Pegboard', { exact: true }).click()
  await page.getByRole('button', { name: 'Add to workspace' }).click()
  await expect(page.locator('.panel-list-row')).toHaveCount(initialCount + 1)
  await expect(page.getByLabel('Panel name')).toHaveValue(`Panel ${initialCount + 1}`)
  await page.getByRole('button', { name: 'Attach a panel', exact: true }).click()
  await expect(page.getByText('Attachment preview', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Left', exact: true }).click()
  await page.getByRole('button', { name: '105° connector', exact: true }).click()
  await page.getByLabel('Offset', { exact: true }).fill('30')
  await page.getByLabel('Offset', { exact: true }).press('Tab')
  await page.screenshot({ path: 'test-results/studio-attachment.png' })
  await page.getByRole('button', { name: 'Attach panel', exact: true }).click()
  await expect(page.locator('.panel-list-row')).toHaveCount(initialCount + 2)
  await page.getByRole('button', { name: 'Undo (⌘/Ctrl Z)' }).click()
  await expect(page.locator('.panel-list-row')).toHaveCount(initialCount + 1)
  await page.getByRole('button', { name: 'Redo (⌘/Ctrl Shift Z)' }).click()
  await expect(page.locator('.panel-list-row')).toHaveCount(initialCount + 2)
  await expect(page.getByText('Saved on this device', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.locator('.panel-list-row')).toHaveCount(initialCount + 2)
  await expect(page.locator('canvas')).toBeVisible()
  expect(errors).toEqual([])
  expect(await page.evaluate(() => ({ horizontal: document.documentElement.scrollWidth > innerWidth, vertical: document.documentElement.scrollHeight > innerHeight }))).toEqual({ horizontal: false, vertical: false })
})

test('templates, dimensions, camera and exports work without outer scrolling', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Show dimensions', exact: true }).click()
  await page.getByRole('combobox', { name: 'Camera view' }).selectOption('front')
  await page.getByRole('button', { name: 'Fit assembly (F)' }).click()
  await page.getByRole('button', { name: 'Templates', exact: true }).click()
  await page.getByRole('button', { name: /Creative display Put your creativity/ }).click()
  await expect(page.getByLabel('Panel name')).toHaveValue('Display base')
  await page.getByRole('button', { name: 'Export project', exact: true }).click()
  const exportPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: /Project file All panels/ }).click()
  expect((await exportPromise).suggestedFilename()).toContain('.playwood.json')
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await page.getByRole('button', { name: 'View parts list', exact: false }).click()
  await expect(page.getByRole('table')).toBeVisible()
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await page.setViewportSize({width: 1000,height: 760})
  expect(await page.evaluate(() => document.documentElement.scrollHeight <= innerHeight)).toBe(true)
  await page.screenshot({path:'test-results/studio-compact.png'})
})

test('existing panels can attach and invalid thickness is blocked', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.panel-list-row').first()).toBeVisible()
  const initialCount = await page.locator('.panel-list-row').count()
  const addedPanelName = `Panel ${initialCount + 1}`
  await page.getByRole('button', { name: 'Add a panel', exact: false }).first().click()
  await page.getByRole('button', { name: 'Add to workspace' }).click()
  await expect(page.locator('.panel-list-row')).toHaveCount(initialCount + 1)
  await page.locator('.panel-list-select').first().click()
  await page.getByRole('button', { name: 'Attach a panel', exact: true }).click()
  await page.getByLabel('Panel to attach').selectOption({label:`${addedPanelName} · existing`})
  await page.getByLabel('Thickness', {exact:true}).fill('25')
  await page.getByLabel('Thickness', {exact:true}).press('Tab')
  await expect(page.getByText('90° connectors need 16–19 mm panels.')).toBeVisible()
  await expect(page.getByRole('button', {name:'Attach panel',exact:true})).toBeDisabled()
  await page.getByLabel('Thickness', {exact:true}).fill('18')
  await page.getByLabel('Thickness', {exact:true}).press('Tab')
  await page.getByRole('button', {name:'Attach panel',exact:true}).click()
  await expect(page.locator('.panel-list-row')).toHaveCount(initialCount + 1)
  await expect(page.getByLabel('Panel name')).toHaveValue(addedPanelName)
  await expect(page.getByText('Attached to', {exact:false})).toBeVisible()
  await page.getByRole('button', {name:'Detach for free placement',exact:false}).click()
  await expect(page.getByLabel('Position X')).toBeVisible()
})

