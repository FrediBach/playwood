import { test, expect } from '@playwright/test'

for (const width of [1440, 390]) test(`filters restore focus and dismiss without blocking the workspace at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 })
  await page.goto('/')
  if (width === 390) await page.getByRole('button', { name: 'Open panel list', exact: true }).click()
  const trigger = page.getByRole('button', { name: 'Filter panels', exact: true })
  const dialog = page.getByRole('dialog', { name: 'Filter panels', exact: true })
  await trigger.click()
  await expect(dialog).toBeInViewport()
  await expect(dialog.getByRole('searchbox')).toBeFocused()
  await expect(trigger).toHaveAttribute('aria-expanded', 'true')
  await dialog.getByRole('searchbox').press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(trigger).toBeFocused()
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  await trigger.click()
  await expect(dialog.getByRole('searchbox')).toBeFocused()
  // An outside action stays usable and light-dismisses the non-modal dialog.
  await page.getByRole('tab', { name: 'Connectors', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('tab', { name: 'Connectors', exact: true })).toHaveAttribute('aria-selected', 'true')
})

test('panel filters combine search and area, reset, and select only matches', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Filter panels', exact: true }).click()
  const popover = page.getByRole('dialog', { name: 'Filter panels' })
  await page.screenshot({ path: 'test-results/panel-filters.png' })
  await popover.getByRole('searchbox').fill('shelf')
  await expect(page.locator('.panel-list-row')).toHaveCount(3)
  await popover.getByLabel('Maximum panel area').fill('0')
  await expect(page.locator('.panel-list-row')).toHaveCount(0)
  await expect(popover.getByRole('status')).toHaveText('0 of 7 panels')
  await popover.getByRole('button', { name: 'Reset filters' }).click()
  await expect(page.locator('.panel-list-row')).toHaveCount(7)
  await popover.getByRole('searchbox').fill('shelf')
  await page.keyboard.press('Escape')
  await expect(popover).not.toBeVisible()
  await page.getByRole('button', { name: 'Select all', exact: true }).click()
  await expect(page.locator('.panel-list-row.selected')).toHaveCount(3)
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await expect(page.locator('.panel-list-row')).toHaveCount(7)
  await expect(page.locator('.panel-list-row.selected')).toHaveCount(3)
})

test('connector filters show empty state, reset, and preserve project hardware', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('tab', { name: 'Connectors', exact: true }).click()
  const rows = page.locator('.connector-list-row')
  const total = await rows.count()
  await page.getByRole('button', { name: 'Filter connectors', exact: true }).click()
  const popover = page.getByRole('dialog', { name: 'Filter connectors' })
  await popover.getByRole('checkbox', { name: 'Cross', exact: true }).check()
  await expect(rows).toHaveCount(0)
  await expect(page.getByText('No matches. Try fewer filters.')).toBeVisible()
  await popover.getByRole('button', { name: 'Reset filters' }).click()
  await expect(rows).toHaveCount(total)
  await popover.getByLabel('Visibility').selectOption('hidden')
  await expect(rows).toHaveCount(0)
  await popover.getByRole('button', { name: 'Reset filters' }).click()
  await popover.getByRole('button', { name: 'Close filters' }).click()
  await expect(page.getByRole('button', { name: 'Filter connectors', exact: true })).toBeFocused()
  await expect(rows).toHaveCount(total)
})
