import { test, expect } from '@playwright/test'
import { createStarterProject, validateProject } from '../src/lib/model'

test('splits selected shelves with a center divider, saves, and undoes as one edit', async ({ page }) => {
  const original = createStarterProject()
  original.panels.forEach(panel => { panel.cornerRadius = 30 })
  await page.goto('/')
  await page.getByLabel('Import project file').setInputFiles({ name: 'rounded-shelf.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(original)) })
  const select = (name: string) => page.locator('.panel-list-row').filter({ has: page.getByText(name, { exact: true }) }).locator('.panel-list-select')
  await select('Top shelf').click()
  await select('Middle shelf').click({ modifiers: ['Shift'] })
  await page.getByRole('button', { name: 'Split in the middle', exact: true }).click()
  await expect(page.locator('.panel-list-row')).toHaveCount(10)
  await expect(page.locator('.panel-list-row.selected')).toHaveCount(5)
  await expect(page.getByText('Center divider', { exact: true })).toBeVisible()
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('playwood-studio-project-v1')!).panels.length)).toBe(10)
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('playwood-studio-project-v1')!))
  expect(validateProject(saved).filter(issue => issue.severity === 'error')).toEqual([])
  expect(saved.connections.length).toBe(original.connections.length + 4)
  await page.screenshot({ path: 'test-results/split-panels.png' })
  await page.getByRole('button', { name: 'Undo (⌘/Ctrl Z)' }).click()
  await expect(page.locator('.panel-list-row')).toHaveCount(7)
  await page.getByRole('button', { name: 'Redo (⌘/Ctrl Shift Z)' }).click()
  await expect(page.locator('.panel-list-row')).toHaveCount(10)
  await expect(page.getByText('Saved on this device', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.locator('.panel-list-row')).toHaveCount(10)
})

test('offers valid split counts and creates evenly sized sections in one undo step', async ({ page }) => {
  const original = createStarterProject()
  await page.goto('/')
  await page.getByLabel('Import project file').setInputFiles({ name: 'shelf.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(original)) })
  const select = (name: string) => page.locator('.panel-list-row').filter({ has: page.getByText(name, { exact: true }) }).locator('.panel-list-select')
  await select('Top shelf').click()
  await select('Middle shelf').click({ modifiers: ['Shift'] })
  const counts = page.getByRole('combobox', { name: 'Number of splits' })
  await expect(counts.locator('option[value="3"]')).toBeAttached()
  await counts.selectOption('3')
  await expect(page.getByRole('img', { name: 'Preview: 3 dividers creating 4 equal sections per panel' })).toBeVisible()
  await page.getByRole('button', { name: 'Fewer dividers', exact: true }).click()
  await expect(counts).toHaveValue('2')
  await page.getByRole('button', { name: 'More dividers', exact: true }).click()
  await expect(counts).toHaveValue('3')
  await page.screenshot({ path: 'test-results/split-controls.png' })
  await page.getByRole('button', { name: 'Add 3 dividers', exact: true }).click()
  await expect(page.locator('.panel-list-row')).toHaveCount(16)
  await expect(page.locator('.panel-list-row.selected')).toHaveCount(11)
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('playwood-studio-project-v1')!).panels.length)).toBe(16)
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('playwood-studio-project-v1')!))
  expect(validateProject(saved)).toEqual([])
  expect(saved.connections.length).toBe(original.connections.length + 12)
  await page.getByRole('button', { name: 'Undo (⌘/Ctrl Z)' }).click()
  await expect(page.locator('.panel-list-row')).toHaveCount(7)
  await page.getByRole('button', { name: 'Redo (⌘/Ctrl Shift Z)' }).click()
  await expect(page.locator('.panel-list-row')).toHaveCount(16)
})

test('removes split controls when selection changes or clears', async ({ page }) => {
  const original = createStarterProject()
  const keyWarnings: string[] = []
  page.on('console', message => { if (message.text().includes('same key')) keyWarnings.push(message.text()) })
  await page.goto('/')
  await page.getByLabel('Import project file').setInputFiles({ name: 'shelf.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(original)) })
  const select = (name: string) => page.locator('.panel-list-row').filter({ has: page.getByText(name, { exact: true }) }).locator('.panel-list-select')
  const split = page.getByRole('region', { name: 'Split parallel panels' })
  for (let attempt = 0; attempt < 2; attempt++) {
    await select('Top shelf').click()
    await select('Middle shelf').click({ modifiers: ['Shift'] })
    await expect(split).toHaveCount(1)
    await expect(page.getByRole('button', { name: 'Split in the middle', exact: true })).toBeEnabled()
    await page.getByRole('checkbox', { name: 'Select Top shelf', exact: true }).uncheck()
    await expect(split).toHaveCount(0)
    await page.getByRole('checkbox', { name: 'Select Middle shelf', exact: true }).uncheck()
    await expect(page.locator('.panel-list-row.selected')).toHaveCount(0)
    await expect(page.getByRole('combobox', { name: 'Number of splits' })).toHaveCount(0)
    await expect(page.getByRole('button', { name: 'Split in the middle', exact: true })).toHaveCount(0)
  }
  await select('Top shelf').click()
  await select('Middle shelf').click({ modifiers: ['Shift'] })
  await expect(split).toHaveCount(1)
  await page.keyboard.press('Escape')
  await expect(page.locator('.panel-list-row.selected')).toHaveCount(0)
  await expect(split).toHaveCount(0)
  expect(keyWarnings).toEqual([])
})
