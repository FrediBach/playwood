test('removes split controls when selection changes or clears', async ({ page }) => {
  const original = createStarterProject()
  const keyWarnings: string[] = []
  page.on('console', message => { if (message.text().includes('same key')) keyWarnings.push(message.text()) })
  await page.goto('/')
  await page.getByLabel('Import project file').setInputFiles({ name: 'shelf.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(original)) })
  const select = (name: string) => page.locator('.panel-list-row').filter({ has: page.getByText(name, { exact: true }) }).locator('.panel-list-select')
  const split = page.getByRole('region', { name: 'Split parallel panels' })
  for (let attempt = 0; attempt < 2; attempt++) {
    await select('Top shelf').click()
    await select('Middle shelf').click({ modifiers: ['Shift'] })
    await openInspectorSection(page, 'Divide evenly')
    await expect(split).toHaveCount(1)
    await expect(page.getByRole('button', { name: 'Split in the middle', exact: true })).toBeEnabled()
    await page.getByRole('checkbox', { name: 'Select Top shelf', exact: true }).uncheck()
    await expect(split).toHaveCount(0)
    await page.getByRole('checkbox', { name: 'Select Middle shelf', exact: true }).uncheck()
    await expect(page.locator('.panel-list-row.selected')).toHaveCount(0)
    await expect(page.getByRole('combobox', { name: 'Number of splits' })).toHaveCount(0)
    await expect(page.getByRole('button', { name: 'Split in the middle', exact: true })).toHaveCount(0)
  }
  await select('Top shelf').click()
  await select('Middle shelf').click({ modifiers: ['Shift'] })
  await openInspectorSection(page, 'Divide evenly')
  await expect(split).toHaveCount(1)
  await page.keyboard.press('Escape')
  await expect(page.locator('.panel-list-row.selected')).toHaveCount(0)
  await expect(split).toHaveCount(0)
  expect(keyWarnings).toEqual([])
})

test('ignores late split worker results after changing selection', async ({ page }) => {
  await page.addInitScript(() => {
    const callbacks: (() => void)[] = []
    Object.assign(window, { deliverOldSplitResults: () => { callbacks.forEach(callback => callback()); return callbacks.length } })
    const OriginalWorker = window.Worker
    window.Worker = class extends OriginalWorker {
      private splitWorker: boolean
      constructor(url: string | URL, options?: WorkerOptions) {
        super(url, options)
        this.splitWorker = String(url).includes('parallel-panel-split.worker')
      }
      terminate() {
        if (this.splitWorker && this.onmessage) {
          const handler = this.onmessage
          callbacks.push(() => handler.call(this, new MessageEvent('message', { data: { counts: [99], checking: false } })))
        }
        super.terminate()
      }
    }
  })
  await page.goto('/')
  await page.getByLabel('Import project file').setInputFiles({ name: 'shelf.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(createStarterProject())) })
  const select = (name: string) => page.locator('.panel-list-row').filter({ has: page.getByText(name, { exact: true }) }).locator('.panel-list-select')
  const counts = page.getByRole('combobox', { name: 'Number of splits' })
  await select('Top shelf').click()
  await select('Middle shelf').click({ modifiers: ['Shift'] })
  await openInspectorSection(page, 'Divide evenly')
  await expect(counts.locator('option[value="3"]')).toBeAttached()
  await select('Top shelf').click()
  await select('Middle shelf').click({ modifiers: ['Shift'] })
  await openInspectorSection(page, 'Divide evenly')
  await expect(counts.locator('option[value="3"]')).toBeAttached()
  const delivered = await page.evaluate(async () => {
    const count = (window as unknown as { deliverOldSplitResults: () => number }).deliverOldSplitResults()
    await new Promise(resolve => requestAnimationFrame(resolve))
    return count
  })
  expect(delivered).toBeGreaterThan(0)
  await expect(counts.locator('option[value="3"]')).toBeAttached()
  await expect(counts.locator('option[value="99"]')).toHaveCount(0)
})

test('divides four selected sides into a grid, validates inputs, saves and undoes', async ({ page }) => {
  const { gridProject } = await import('../src/lib/example-geometry')
  const original = gridProject('Grid opening', [900], [600])
  await page.goto('/')
  await page.getByLabel('Import project file').setInputFiles({ name: 'opening.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(original)) })
  await page.getByRole('button', { name: 'Select all', exact: true }).click()
  await openInspectorSection(page, 'Divide into a grid')
  const grid = page.getByRole('region', { name: 'Split opening into a grid' })
  await expect(grid).toBeVisible()
  await page.getByRole('button', { name: 'Clear', exact: true }).click()
  await expect(grid).toHaveCount(0)
  await page.getByRole('button', { name: 'Select all', exact: true }).click()
  await openInspectorSection(page, 'Divide into a grid')
  await expect(grid).toBeVisible()
  await expect(page.getByRole('region', { name: 'Split parallel panels' })).toHaveCount(0)
  const x = page.getByRole('spinbutton', { name: 'X dividers', exact: true })
  const y = page.getByRole('spinbutton', { name: 'Y dividers', exact: true })
  await x.fill('2')
  await y.fill('1')
  const apply = page.getByRole('button', { name: 'Create 3 × 2 grid', exact: true })
  await expect(apply).toBeEnabled()
  await expect(page.getByRole('img', { name: 'Grid preview: 3 columns and 2 rows' })).toBeVisible()
  await page.screenshot({ path: 'test-results/grid-split-controls.png' })
  await x.fill('100')
  await expect(grid.locator('.panel-split-apply')).toBeDisabled()
  await x.fill('2')
  await expect(apply).toBeEnabled()
  await apply.click()
  await expect(page.locator('.panel-list-row')).toHaveCount(17)
  await expect(grid).toHaveCount(0)
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('playwood-studio-project-v1')!).panels.length)).toBe(17)
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('playwood-studio-project-v1')!))
  expect(validateProject(saved)).toEqual([])
  expect(saved.connections.filter((c: { type: string }) => c.type === 'cross')).toHaveLength(6)
  await page.screenshot({ path: 'test-results/grid-split-result.png' })
  await page.getByRole('button', { name: 'Undo (⌘/Ctrl Z)' }).click()
  await expect(page.locator('.panel-list-row')).toHaveCount(4)
  await page.getByRole('button', { name: 'Redo (⌘/Ctrl Shift Z)' }).click()
  await expect(page.locator('.panel-list-row')).toHaveCount(17)
  await page.reload()
  await expect(page.locator('.panel-list-row')).toHaveCount(17)
})

test('context split submenu selects an axis and disables cuts without room', async ({ page }) => {
  await page.goto('/')
  const load = async (height: number) => {
    const project = { version: 1, name: 'Axis split', connections: [], panels: [
      createPanel({ id: 'a', name: 'Front', width: 900, height, position: [0, 500, 0] }),
      createPanel({ id: 'b', name: 'Back', width: 900, height, position: [0, 500, 400] }),
    ] }
    await page.getByLabel('Import project file').setInputFiles({ name: 'pair.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(project)) })
    await page.getByRole('checkbox', { name: 'Select Front', exact: true }).check()
    await page.getByRole('checkbox', { name: 'Select Back', exact: true }).check()
    await page.locator('canvas').focus()
    await page.keyboard.press('Shift+F10')
    await page.getByRole('menuitem', { name: 'Split in the middle', exact: true }).click()
  }
  await load(300)
  const submenu = page.getByRole('menu', { name: 'Split in the middle', exact: true })
  await expect(submenu.getByRole('menuitem', { name: 'Local Y · Height' })).toBeEnabled()
  await expect(submenu.getByRole('menuitem', { name: 'Local Z · Thickness' })).toBeDisabled()
  await submenu.getByRole('menuitem', { name: 'Local Y · Height' }).click()
  await expect(page.locator('.panel-list-row')).toHaveCount(5)
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('playwood-studio-project-v1')!).panels.length)).toBe(5)
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('playwood-studio-project-v1')!))
  expect(saved.panels.filter((panel: { name: string }) => panel.name !== 'Center divider').every((panel: { width: number; height: number }) => panel.width === 900 && Math.abs(panel.height - 132.5) < 0.01)).toBe(true)
  expect(validateProject(saved)).toEqual([])
  await page.getByRole('button', { name: 'Undo (⌘/Ctrl Z)' }).click()
  await expect(page.locator('.panel-list-row')).toHaveCount(2)
  await load(100)
  await expect(submenu.getByRole('menuitem', { name: 'Local X · Width' })).toBeEnabled()
  await expect(submenu.getByRole('menuitem', { name: 'Local Y · Height' })).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(submenu).toHaveCount(0)
  await expect(page.getByRole('menuitem', { name: 'Split in the middle', exact: true })).toBeFocused()
})
