test('immediate reload retains an edit before the autosave debounce',async({page})=>{
  await page.goto('/')
  await expect(page.locator('.panel-list-row')).toHaveCount(7)
  await expect.poll(()=>savedName(page),{timeout:15000}).toBeTruthy()
  await rename(page,'Pending edit')
  await page.reload()
  await expect(page.locator('.project-name')).toHaveText('Pending edit')
  await expect.poll(()=>savedName(page),{timeout:15000}).toBe('Pending edit')
})

test('two delayed autosaves cannot silently replace each other',async({page,context})=>{
  await page.goto('/')
  await expect(page.locator('.panel-list-row')).toHaveCount(7)
  await expect.poll(()=>savedName(page),{timeout:15000}).toBeTruthy()
  const other=await context.newPage()
  await other.goto('/')
  await expect(other.locator('.panel-list-row')).toHaveCount(7)
  await page.evaluate(key=>{
    const state=window as unknown as {releaseSaveLock:()=>void}
    void navigator.locks.request(key,()=>new Promise<void>(resolve=>{state.releaseSaveLock=resolve}))
  },key)
  await expect.poll(()=>page.evaluate(()=>typeof (window as unknown as {releaseSaveLock?:()=>void}).releaseSaveLock)).toBe('function')
  await rename(page,'Writer A')
  await rename(other,'Writer B')
  await expect.poll(()=>page.evaluate(async key=>(await navigator.locks.query()).pending?.filter(lock=>lock.name===key).length,key)).toBe(2)
  await page.evaluate(()=>(window as unknown as {releaseSaveLock:()=>void}).releaseSaveLock())
  await expect.poll(()=>savedName(page)).toMatch(/^Writer [AB]$/)
  const winner=await savedName(page)
  const loser=winner==='Writer A'?other:page
  await expect(loser.getByRole('alert')).toContainText('Another tab changed')
  await loser.reload()
  await expect(loser.locator('.project-name')).toHaveText(winner==='Writer A'?'Writer B':'Writer A')
  expect(await savedName(page)).toBe(winner)
})
