import {test,expect,type Page} from '@playwright/test'
const key='playwood-studio-project-v1'
async function rename(page:Page,name:string) {
  await page.locator('.project-name').click()
  await page.getByRole('textbox',{name:'Project name',exact:true}).fill(name)
  await page.getByRole('textbox',{name:'Project name',exact:true}).press('Enter')
}
async function savedName(page:Page) {
  return page.evaluate(key=>JSON.parse(localStorage.getItem(key)??'{}').name,key)
}
test('stale tab exit cannot overwrite the newer save; conflict switching preserves both',async({page,context})=>{
  await page.goto('/')
  await expect(page.locator('.panel-list-row')).toHaveCount(7)
  await expect.poll(()=>savedName(page),{timeout:15000}).toBeTruthy()
  const stale=await context.newPage()
  await stale.goto('/')
  await expect(stale.locator('.panel-list-row')).toHaveCount(7)
  await rename(page,'Newer save')
  await expect.poll(()=>savedName(page)).toBe('Newer save')
  await expect(stale.getByRole('alert')).toContainText('Another tab changed')
  await rename(stale,'My divergent work')
  await stale.waitForTimeout(600)
  expect(await savedName(stale)).toBe('Newer save')
  expect(await stale.evaluate(key=>Object.keys(localStorage).some(k=>k.startsWith(`${key}-recovery-`)&&JSON.parse(localStorage.getItem(k)!).name==='My divergent work'),key)).toBe(true)
  await stale.reload()
  await expect(stale.locator('.project-name')).toHaveText('My divergent work')
  await expect(stale.getByRole('alert')).toContainText('Another tab changed')
  await stale.getByRole('button',{name:'Open browser save',exact:true}).click()
  await expect(stale.locator('.project-name')).toHaveText('Newer save')
  expect(await stale.evaluate(key=>Object.keys(localStorage).some(k=>k.startsWith(`${key}-recovery-`)&&JSON.parse(localStorage.getItem(k)!).name==='My divergent work'),key)).toBe(true)
  await stale.goto('about:blank')
  expect(await savedName(page)).toBe('Newer save')
})
