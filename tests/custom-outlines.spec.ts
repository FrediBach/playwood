import { expect, test, type Page } from '@playwright/test'
import { createPanel } from '../src/lib/model'
import type { Project } from '../src/lib/types'

async function openPanel(page: Page) {
  const project: Project = {
    version: 1, name: 'Outline workbench', connections: [],
    panels: [createPanel({ id: 'outline-panel', name: 'Outline panel', width: 600, height: 400, position: [0, 200, 0] })],
  }
  await page.goto('/')
  await page.getByLabel('Import project file').setInputFiles({
    name: 'outline.playwood.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(project)),
  })
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.locator('.panel-list-select').first().click()
}

async function coordinate(page: Page, name: string, value: string) {
  const field = page.getByRole('spinbutton', { name, exact: true })
  await field.fill(value)
  await field.press('Tab')
}

const outlineDialog = (page: Page) => page.getByRole('dialog', { name: 'Edit panel outline', exact: true })

test('precise outline edits, local history, rounding, scaling, and autosave work together', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await openPanel(page)
  await page.getByRole('button', { name: 'Create custom outline', exact: true }).click()
  await expect(outlineDialog(page)).toBeVisible()
  await page.getByRole('button', { name: 'Add point after selected', exact: true }).click()
  await expect(page.getByRole('spinbutton', { name: 'Point 2 X', exact: true })).toHaveValue('300')
  await coordinate(page, 'Point 2 X', '320.25')
  await coordinate(page, 'Point 2 Y', '15.5')
  await page.getByRole('button', { name: 'Undo outline edit', exact: true }).click()
  await expect(page.getByRole('spinbutton', { name: 'Point 2 Y', exact: true })).toHaveValue('0')
  await page.getByRole('button', { name: 'Redo outline edit', exact: true }).click()
  await expect(page.getByRole('spinbutton', { name: 'Point 2 Y', exact: true })).toHaveValue('15.5')
  await coordinate(page, 'Outline corner radius', '12.5')
  await page.getByRole('button', { name: 'Apply outline', exact: true }).click()
  await expect(outlineDialog(page)).not.toBeVisible()
  const preview = page.getByRole('img', { name: 'Custom outline preview', exact: true })
  await expect(preview).toBeVisible()
  await expect(page.getByRole('spinbutton', { name: 'Corner radius', exact: true })).toHaveValue('12.5')
  const roundedPath = await preview.locator('path').first().getAttribute('d')
  expect(roundedPath).toMatch(/[AQ]/)
  await coordinate(page, 'Width', '1200')
  await coordinate(page, 'Height', '600')
  await expect(page.getByText('Saved on this device', { exact: true })).toBeVisible()
  await page.reload()
  await page.locator('.panel-list-select').first().click()
  await expect(preview).toBeVisible()
  await page.getByRole('button', { name: 'Edit custom outline', exact: true }).click()
  await expect(page.getByRole('spinbutton', { name: 'Point 2 X', exact: true })).toHaveValue('640.5')
  await expect(page.getByRole('spinbutton', { name: 'Point 2 Y', exact: true })).toHaveValue('23.25')
  await expect(page.getByRole('spinbutton', { name: 'Outline corner radius', exact: true })).toHaveValue('12.5')
  await page.screenshot({ path: 'test-results/custom-outline-editor.png' })
  await coordinate(page, 'Point 2 Y', '99')
  await coordinate(page, 'Outline corner radius', '30')
  await outlineDialog(page).getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Edit custom outline', exact: true }).click()
  await expect(page.getByRole('spinbutton', { name: 'Point 2 Y', exact: true })).toHaveValue('23.25')
  await expect(page.getByRole('spinbutton', { name: 'Outline corner radius', exact: true })).toHaveValue('12.5')
  expect(errors).toEqual([])
})

