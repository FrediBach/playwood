test('dragging and keyboard nudges move points without moving the underlying panel', async ({ page }) => {
  await openPanel(page)
  await page.getByRole('button', { name: 'Create custom outline', exact: true }).click()
  const point = outlineDialog(page).getByRole('button', { name: 'Point 1', exact: true })
  const bounds = await point.boundingBox()
  expect(bounds).not.toBeNull()
  await page.mouse.move(bounds!.x + bounds!.width / 2, bounds!.y + bounds!.height / 2)
  await page.mouse.down()
  await page.mouse.move(bounds!.x + bounds!.width / 2 + 45, bounds!.y + bounds!.height / 2 + 35, { steps: 6 })
  await page.mouse.up()
  const xField = page.getByRole('spinbutton', { name: 'Point 1 X', exact: true })
  const yField = page.getByRole('spinbutton', { name: 'Point 1 Y', exact: true })
  const draggedX = Number(await xField.inputValue())
  const draggedY = Number(await yField.inputValue())
  expect(draggedX).toBeGreaterThan(0)
  expect(draggedY).toBeGreaterThan(0)
  await page.getByRole('button', { name: 'Undo outline edit', exact: true }).click()
  await expect(xField).toHaveValue('0')
  await expect(yField).toHaveValue('0')
  await page.getByRole('button', { name: 'Redo outline edit', exact: true }).click()
  expect(Number(await xField.inputValue())).toBe(draggedX)
  await point.focus()
  await point.press('ArrowRight')
  expect(Number(await xField.inputValue())).toBeGreaterThan(draggedX)
  await page.getByRole('button', { name: 'Apply outline', exact: true }).click()
  await expect(page.getByRole('spinbutton', { name: 'Position X', exact: true })).toHaveValue('0')
  await expect(page.getByRole('spinbutton', { name: 'Position Y', exact: true })).toHaveValue('200')
})

test('cancel discards a new outline, and removal is a single undoable project change', async ({ page }) => {
  await openPanel(page)
  await page.getByRole('button', { name: 'Create custom outline', exact: true }).click()
  await coordinate(page, 'Point 1 X', '120')
  await outlineDialog(page).getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Create custom outline', exact: true })).toBeVisible()
  await expect(page.getByRole('img', { name: 'Custom outline preview', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Create custom outline', exact: true }).click()
  await expect(page.getByRole('spinbutton', { name: 'Point 1 X', exact: true })).toHaveValue('0')
  await coordinate(page, 'Point 1 X', '120')
  await page.getByRole('button', { name: 'Apply outline', exact: true }).click()
  const preview = page.getByRole('img', { name: 'Custom outline preview', exact: true })
  await expect(preview).toBeVisible()
  const originalPath = await preview.locator('path').first().getAttribute('d')
  await page.getByRole('button', { name: 'Remove custom outline', exact: true }).click()
  await expect(preview).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Create custom outline', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Undo (⌘/Ctrl Z)', exact: true }).click()
  await expect(preview.locator('path').first()).toHaveAttribute('d', originalPath!)
  await page.getByRole('button', { name: 'Redo (⌘/Ctrl Shift Z)', exact: true }).click()
  await expect(preview).toHaveCount(0)
})

